"""Pydantic schemas — every LLM boundary in MedGraph is typed.

Nothing generated by a model reaches a caller without passing validation here.
Malformed output is rejected at the node that produced it, not downstream.

A note on why fields that look optional have no defaults: Groq's strict
structured-output mode requires every property to appear in the schema's
`required` list with `additionalProperties: false`. A Pydantic field carrying a
default is emitted as *not* required and the request is rejected with a 400. So
optionality is modelled as "required but nullable" (`str | None` with no
default) rather than "has a default". The model must still emit the key; it may
emit null.
"""
from __future__ import annotations

from enum import Enum
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator


class QueryIntent(str, Enum):
    COVERAGE = "coverage"          # is this covered / prior-auth question
    DRUG_INFO = "drug_info"        # label, interactions, contraindications
    GUIDELINE = "guideline"        # clinical guideline lookup
    OUT_OF_SCOPE = "out_of_scope"  # not answerable from the corpus


class StrictModel(BaseModel):
    """Base for every schema handed to a provider as a structured-output target."""

    model_config = ConfigDict(extra="forbid")


# --------------------------------------------------------------------------
# LLM output targets — these shapes are generated by a model
# --------------------------------------------------------------------------

class Classification(StrictModel):
    intent: QueryIntent
    confidence: float = Field(ge=0.0, le=1.0)
    # No max_length. A cap on a free-text reasoning field is tidiness, not a
    # constraint worth enforcing: a verbose model then fails validation and the
    # whole node raises. That happened — a 3,000-character deliberation on the
    # verify node took the run down. Bound what matters, not prose length.
    reasoning: str = Field(min_length=1)


class ClinicalEntity(StrictModel):
    text: str = Field(min_length=1)
    kind: Literal["condition", "procedure", "drug", "code", "payer", "date"]
    code_system: str | None = Field(
        description="ICD-10, CPT, HCPCS, NDC or RxNorm when identifiable, else null"
    )
    code: str | None = Field(description="the code itself when identifiable, else null")


class Extraction(StrictModel):
    entities: list[ClinicalEntity]
    normalized_query: str = Field(min_length=1)


class Synthesis(StrictModel):
    """What `synthesize` is allowed to produce.

    Deliberately NOT `Answer`. The model returns the ids of sources it actually
    used; the `Citation` objects are looked up from what `retrieve` returned.
    Letting a model emit Citation objects directly invites fabricated source_ids,
    which would defeat the entire premise of the system.
    """

    answer: str = Field(min_length=1)
    cited_source_ids: list[str] = Field(
        description="ids of the provided sources actually used; must be a subset of them"
    )


class VerificationResult(StrictModel):
    """Claim-to-citation entailment check over a drafted answer."""

    grounded: bool = Field(description="true only if every claim maps to a cited source")
    unsupported_claims: list[str] = Field(
        description="material claims the sources do not support; [] if none"
    )
    reasoning: str = Field(min_length=1)   # see Classification.reasoning


# --------------------------------------------------------------------------
# Internal shapes — constructed in Python, never generated by a model
# --------------------------------------------------------------------------

class Citation(BaseModel):
    source_id: str
    title: str
    url: str | None = None
    snippet: str = Field(max_length=1200)
    score: float = Field(ge=0.0, le=1.0)


class Answer(BaseModel):
    """Final response.

    The grounding invariant is enforced here rather than in a prompt: a non-refused
    answer must be non-empty AND carry at least one citation, and a refusal must
    state why. An ungrounded answer cannot be constructed at all.
    """

    answer: str = ""
    citations: list[Citation] = Field(default_factory=list)
    refused: bool = False
    refusal_reason: str | None = None

    @model_validator(mode="after")
    def _enforce_grounding(self):
        if self.refused:
            if not (self.refusal_reason or "").strip():
                raise ValueError("a refusal must state a reason")
            return self
        if not self.answer.strip():
            raise ValueError("a non-refused answer must not be empty")
        if not self.citations:
            raise ValueError("a non-refused answer must carry at least one citation")
        return self


class LLMCall(BaseModel):
    """One provider call. Written to `runs` so daily token budgets are enforceable."""

    node: str
    provider: str
    model: str
    input_tokens: int = 0
    output_tokens: int = 0
    latency_ms: int = 0
    fell_back: bool = False   # a provider in this node's chain failed first


class RunTrace(BaseModel):
    """Per-run observability record, persisted for evaluation and cost tracking."""

    run_id: str
    nodes_visited: list[str] = Field(default_factory=list)
    calls: list[LLMCall] = Field(default_factory=list)
    latency_ms: int = 0

    @property
    def input_tokens(self) -> int:
        return sum(c.input_tokens for c in self.calls)

    @property
    def output_tokens(self) -> int:
        return sum(c.output_tokens for c in self.calls)

    @property
    def fallbacks(self) -> int:
        """Calls that a provider failure pushed down the chain."""
        return sum(1 for c in self.calls if c.fell_back)

    @property
    def cost_usd(self) -> float:
        """Zero by construction — every provider in use is a free tier.

        Kept as a real field rather than deleted: the column exists in `runs`, and
        a swap to a paid provider makes this meaningful without a schema change.
        """
        return 0.0
